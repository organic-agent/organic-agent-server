-- photo_ratings는 사진당 한 줄을 덮어쓴다. 지나간 점수·지운 기록은 여기에 한 줄씩 쌓는다.
-- photo_ratings 행이 실제로 바뀐 커밋에만 한 줄이다 — rating_revision이 오르는 커밋과 같다.
-- score NULL은 지움. 사진 영구 삭제·탈퇴는 photo_ratings와 같이 CASCADE로 지운다.
CREATE TABLE photo_rating_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id BIGINT NOT NULL,
    score INTEGER NULL,
    rated_by BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_photo_rating_history_photo FOREIGN KEY (photo_id) REFERENCES photos(id) ON DELETE CASCADE,
    CONSTRAINT fk_photo_rating_history_user FOREIGN KEY (rated_by) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_photo_rating_history_score CHECK (score IS NULL OR score BETWEEN 1 AND 5)
);

-- 사진 한 장의 최신 기록 50건 조회.
CREATE INDEX idx_photo_rating_history_photo_id_id ON photo_rating_history(photo_id, id DESC);
-- 탈퇴 시 CASCADE가 훑는다.
CREATE INDEX idx_photo_rating_history_rated_by ON photo_rating_history(rated_by);
