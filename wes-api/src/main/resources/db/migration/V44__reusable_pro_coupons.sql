ALTER TABLE pro_coupons
    DROP CONSTRAINT pro_coupons_code_suffix_check,
    ADD CONSTRAINT pro_coupons_code_suffix_check CHECK (code_suffix ~ '^[A-Z0-9_-]{1,8}$'),
    ADD COLUMN custom_code varchar(80) CHECK (custom_code ~ '^[A-Z0-9][A-Z0-9_-]*$'),
    ADD COLUMN usage_policy varchar(20) NOT NULL DEFAULT 'SINGLE_USE'
        CHECK (usage_policy IN ('SINGLE_USE', 'ONCE_PER_ACCOUNT', 'UNLIMITED')),
    ADD COLUMN redeem_until timestamptz,
    ADD COLUMN use_count bigint NOT NULL DEFAULT 0 CHECK (use_count >= 0);

ALTER TABLE pro_coupons DROP CONSTRAINT ck_pro_coupons_disabled_unused;
ALTER TABLE pro_coupons ADD CONSTRAINT ck_pro_coupons_disabled_unused
    CHECK (usage_policy <> 'SINGLE_USE' OR disabled_at IS NULL OR consumed_at IS NULL);

CREATE TABLE pro_coupon_registrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id bigint NOT NULL REFERENCES pro_coupons(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (coupon_id, user_id)
);
CREATE INDEX idx_pro_coupon_registrations_user ON pro_coupon_registrations(user_id, created_at DESC, id DESC);

CREATE TABLE pro_coupon_uses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id bigint NOT NULL REFERENCES pro_coupons(id) ON DELETE CASCADE,
    user_id bigint REFERENCES users(id) ON DELETE SET NULL,
    gallery_id bigint UNIQUE REFERENCES galleries(id) ON DELETE SET NULL,
    consumed_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL CHECK (expires_at > consumed_at),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_pro_coupon_uses_coupon ON pro_coupon_uses(coupon_id, consumed_at DESC, id DESC);
CREATE INDEX idx_pro_coupon_uses_user ON pro_coupon_uses(coupon_id, user_id, consumed_at DESC, id DESC);

INSERT INTO pro_coupon_uses (coupon_id, user_id, gallery_id, consumed_at, expires_at, created_at, updated_at)
SELECT id, user_id, gallery_id, consumed_at, expires_at, consumed_at, consumed_at
FROM pro_coupons WHERE consumed_at IS NOT NULL;
UPDATE pro_coupons SET use_count = 1 WHERE consumed_at IS NOT NULL;
