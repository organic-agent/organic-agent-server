             'SELECTION_SUBMITTED', 'RETOUCH_REQUESTED', 'RETOUCH_COMPLETED', 'INVITE_ACCEPTED', 'RETOUCH_CONFIRMED',
             'SELECTION_REOPENED', 'GALLERY_OPENED', 'GALLERY_REOPENED', 'SELECTION_INCREASE_REQUESTED',
             'SELECTION_INCREASE_APPROVED', 'PLAN_EXPIRED', 'DEADLINE_REMINDER', 'PLAN_EXPIRY_REMINDER',
             'ANALYSIS_COMPLETED', 'ALBUM_SENT', 'ALBUM_RETURNED', 'ALBUM_CONFIRMED')
);
