ALTER TABLE public.galleries DROP CONSTRAINT ck_galleries_stage;
ALTER TABLE public.galleries ADD CONSTRAINT ck_galleries_stage CHECK (
    stage IN ('UPLOAD', 'SELECTION_IN_PROGRESS', 'SELECTION_COMPLETED', 'RETOUCH', 'DELIVERY', 'ALBUM', 'ARCHIVED')
);
ALTER TABLE public.galleries ADD COLUMN album_status varchar(20) NOT NULL DEFAULT 'NONE';
ALTER TABLE public.galleries ADD CONSTRAINT ck_galleries_album_status CHECK (
    album_status IN ('NONE', 'DRAFT', 'SENT_EDIT', 'RETURNED', 'CONFIRMED')
);

CREATE TABLE public.gallery_albums (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gallery_id bigint NOT NULL UNIQUE REFERENCES public.galleries(id) ON DELETE CASCADE,
    studio_document jsonb NOT NULL CHECK (jsonb_typeof(studio_document) = 'object'),
    sent_document jsonb CHECK (jsonb_typeof(sent_document) = 'object'),
    client_document jsonb CHECK (jsonb_typeof(client_document) = 'object'),
    confirmed_document jsonb CHECK (jsonb_typeof(confirmed_document) = 'object'),
    share_mode varchar(10) CHECK (share_mode IN ('VIEW', 'EDIT')),
    sent_at timestamptz,
    revision bigint NOT NULL CHECK (revision > 0),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz,
    updated_at timestamptz,
    CONSTRAINT ck_gallery_albums_share CHECK (
        (sent_at IS NULL AND sent_document IS NULL AND share_mode IS NULL) OR
        (sent_at IS NOT NULL AND sent_document IS NOT NULL AND share_mode IS NOT NULL)
    )
);

ALTER TABLE public.user_notifications DROP CONSTRAINT ck_user_notifications_type;
ALTER TABLE public.user_notifications ADD CONSTRAINT ck_user_notifications_type CHECK (
