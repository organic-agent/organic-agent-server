package com.soma.wes.photo.domain

/**
 * 원본 하나(지문)가 이 갤러리에서 어떤 상태인가. web 이 폴더를 통째로 다시 던졌을 때 무엇을 올리고 무엇을 건너뛸지 정하는 값이다.
 * 넷 다 API 계약이다 — 지문 조회는 넷을, 발급 응답은 앞의 셋을 돌려준다.
 */
enum class UploadState {

    /** 이 갤러리에 없는 원본. 올리면 새 사진 행이 생긴다. */
    NEW,

    /** 사진 행은 있는데 아직 원본이 올라오지 않았다. 같은 행으로 URL 을 다시 받아 이어 올린다. */
    PENDING,

    /** 이미 올라왔다. 다시 올릴 필요가 없다. */
    UPLOADED,

    /** 같은 원본이 휴지통에 있다. web 은 기본으로 건너뛰고, 사용자가 원하면 새 사진으로 올린다(휴지통 사진은 그대로 남는다). */
    TRASHED,
}
