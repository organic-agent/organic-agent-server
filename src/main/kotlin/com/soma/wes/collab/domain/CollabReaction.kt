package com.soma.wes.collab.domain

/**
 * 하객이 사진 한 장에 남기는 반응.
 *
 * 별점(1~5)이 아니라 세 갈래인 것이 중요하다. 하객은 사진을 스치듯 넘겨보므로 5단계를 주면
 * 3점과 4점의 차이를 저마다 다르게 쓰고, 그렇게 모인 평균은 부부에게 아무 말도 해주지 않는다.
 * 부부가 알고 싶은 것은 "이 사진이 남들 눈에도 괜찮은가"이고, 그 답은 세 칸이면 충분하다.
 *
 * [com.soma.wes.photo.domain.PhotoRating]과 다른 축이다. 저쪽은 부부와 작가가 고르며 남기는
 * 표시라 하객에게 보이지 않고, 이쪽은 하객이 남기는 것이라 사람 수만큼 쌓인다.
 */
enum class CollabReaction {

    /** 좋다. */
    GOOD,

    /** 그저 그렇다. */
    SOSO,

    /** 별로다. */
    BAD,
}
