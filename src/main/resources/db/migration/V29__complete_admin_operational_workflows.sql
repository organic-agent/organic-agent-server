CREATE FUNCTION reject_admin_selection_revision_update() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'admin selection revisions are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_admin_selection_revisions_immutable
    BEFORE UPDATE ON admin_selection_revisions
    FOR EACH ROW EXECUTE FUNCTION reject_admin_selection_revision_update();

