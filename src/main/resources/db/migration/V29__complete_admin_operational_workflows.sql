-- 외부 작업 실행 여부와 사용자에게 보이는 사진 상태를 분리한다. 디스패처가 없는 작업은
-- PENDING으로 남으며, 관리 API가 성공으로 위장하지 않는다.
CREATE TABLE admin_processing_jobs
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type       VARCHAR(40)              NOT NULL,
    status         VARCHAR(20)              NOT NULL,
    target_type    VARCHAR(40)              NOT NULL,
    target_id      BIGINT                   NOT NULL,
    revision_id    BIGINT,
    payload        JSONB                    NOT NULL DEFAULT '{}'::JSONB,
    attempt_count  INTEGER                  NOT NULL DEFAULT 0,
    failure_code   VARCHAR(80),
    last_run_at    TIMESTAMP WITH TIME ZONE,
    actor_admin_id BIGINT,
    reason         VARCHAR(500)             NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_admin_processing_job_type
        CHECK (job_type IN ('DERIVATIVE', 'EMBEDDING', 'QUALITY_ANALYSIS', 'MOCK_RECALCULATION')),
    CONSTRAINT ck_admin_processing_job_status
        CHECK (status IN ('PENDING', 'DISPATCHING', 'DISPATCHED', 'SUCCEEDED', 'FAILED', 'CANCELED'))
);

CREATE UNIQUE INDEX uk_admin_processing_job_revision_type
    ON admin_processing_jobs (job_type, target_type, target_id, revision_id)
    WHERE revision_id IS NOT NULL;
CREATE INDEX idx_admin_processing_jobs_target
    ON admin_processing_jobs (target_type, target_id, created_at DESC);

