-- 최고 관리자 운영 화면에서 실행하는 도메인별 복구 작업과 리비전을 기록한다.

ALTER TABLE admin_idempotency_keys DROP CONSTRAINT ck_admin_idempotency_status;
ALTER TABLE admin_idempotency_keys
    ADD CONSTRAINT ck_admin_idempotency_status
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED', 'CANCELED'));

-- status는 초대 사용자가 볼 수 있는 공개 단계(DRAFT/OPEN/CLOSED)다. 운영 진행 단계는
-- 별도 컬럼으로 분리해 "공개는 닫았지만 납품 작업은 진행 중" 같은 상태를 잃지 않는다.
ALTER TABLE galleries
    ADD COLUMN workflow_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    ADD CONSTRAINT ck_galleries_workflow_status
        CHECK (workflow_status IN ('DRAFT', 'IN_PROGRESS', 'COMPLETED', 'ARCHIVED'));

-- 스튜디오의 기존 user_id는 소유자다. 추가 운영 구성원은 별도 관계로 관리한다.
CREATE TABLE studio_members
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id  BIGINT                   NOT NULL,
    user_id    BIGINT                   NOT NULL,
    role       VARCHAR(20)              NOT NULL,
    version    BIGINT                   NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_studio_members_studio FOREIGN KEY (studio_id) REFERENCES studios (id) ON DELETE CASCADE,
    CONSTRAINT fk_studio_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_studio_members_studio_user UNIQUE (studio_id, user_id),
    CONSTRAINT ck_studio_members_role CHECK (role IN ('OWNER', 'MEMBER'))
);

CREATE INDEX idx_studio_members_user ON studio_members (user_id, studio_id);

