package com.soma.wes.auth.domain

/**
 * 재발급 요청에 온 refresh 토큰을 저장된 토큰과 견준 결과([RefreshTokenEntity.match]).
 *
 * 받아 주는 것은 [MATCH] 하나다. 나머지는 모두 거절하되, [REUSED]만 저장된 토큰까지 지운다.
 */
enum class RefreshTokenMatch {
    /** 마지막으로 발급한 토큰이다. 재발급한다. */
    MATCH,

    /** 저장된 토큰이 없거나 만료됐다. 로그아웃했거나 오래 쓰지 않았다. */
    MISSING,

    /**
     * 다른 로그인이 만든 옛 토큰이다. 다른 기기에서 다시 로그인해 토큰이 갈린 정상 흐름이라 거절만 한다.
     * 로그인 묶음을 모르는 V54 이전 토큰도 여기로 온다 — 재사용인지 가를 수 없어 탈취로 보지 않는다.
     */
    SUPERSEDED,

    /**
     * 같은 로그인에서 방금 교체된 토큰이다. 브라우저 탭 둘이 동시에 재발급하면 늦은 쪽이 옛 토큰을 들고 온다.
     * 웹은 거절을 받으면 다른 탭이 저장한 최신 토큰으로 다시 시도하므로, 저장된 토큰을 지우지 않고 거절만 한다.
     */
    RACED,

    /**
     * 같은 로그인에서 이미 교체된 토큰이 유예 시간이 지나 다시 왔다. 토큰이 복사돼 두 곳에서 쓰이고 있다는 신호다.
     * 누가 최신 토큰을 들고 있는지 알 수 없으므로 저장된 토큰을 지워 그 로그인을 끊는다.
     */
    REUSED,
}
